package br.com.bauzin.market.panic.panicscanner.application.replay;

import br.com.bauzin.market.panic.panicscanner.application.*;
import br.com.bauzin.market.panic.panicscanner.application.engine.TechnicalAnalysisEngine;
import br.com.bauzin.market.panic.panicscanner.application.entry.EntryAnalyzer;
import br.com.bauzin.market.panic.panicscanner.application.usecase.*;
import br.com.bauzin.market.panic.panicscanner.domain.analysis.*;
import br.com.bauzin.market.panic.panicscanner.domain.entry.RankingMode;
import br.com.bauzin.market.panic.panicscanner.domain.strategy.*;
import java.math.*;
import java.time.*;
import java.util.*;

/** Signals are generated by bounded replay first; future prices are accessible only to evaluation. */
public final class PanicOpportunityStudy {
    public enum Classification { DETECTED_EARLY, LOST_AFTER_DETECTION, MISSED_OPPORTUNITY,
        FALSE_POSITIVE, NO_OPPORTUNITY, INSUFFICIENT_FUTURE_DATA }
    public record Settings(LocalDate from, LocalDate to, String historicalProvider, RankingMode rankingMode,
                           BigDecimal return5ThresholdPercent, BigDecimal return10ThresholdPercent,
                           int futureCalendarDays, List<String> tickers, PanicScannerProperties momentum,
                           Object entry, int schema) {
        public Settings {
            Objects.requireNonNull(from); Objects.requireNonNull(to);
            if (from.isAfter(to) || return5ThresholdPercent.signum() <= 0 || return10ThresholdPercent.signum() <= 0
                    || futureCalendarDays < 14) throw new IllegalArgumentException("Invalid study dates/thresholds/future window");
            tickers = List.copyOf(tickers);
        }
    }
    public record Observation(PanicHistoricalReplayRunner.Row signal, BigDecimal return3Percent,
                              BigDecimal return5Percent, BigDecimal return10Percent, LocalDate date3,
                              LocalDate date5, LocalDate date10, Classification classification,
                              LocalDate lastQualifiedDate, Integer lastQualifiedScore, Integer sessionsSinceLastSignal,
                              boolean lostExclusivelyByRsiAbove70) {}
    public record TickerResult(String ticker, List<Observation> observations, String error) {}

    private final MarketDataClient source;
    private final TechnicalAnalysisEngine engine;
    private final ScannerStrategy strategy;
    private final EntryAnalyzer entry;
    private final PanicScannerProperties properties;
    public PanicOpportunityStudy(MarketDataClient source, TechnicalAnalysisEngine engine, ScannerStrategy strategy,
                                 EntryAnalyzer entry, PanicScannerProperties properties) {
        this.source = source; this.engine = engine; this.strategy = strategy; this.entry = entry; this.properties = properties;
    }

    public TickerResult studyTicker(String ticker, Settings settings) {
        // One acquisition per ticker includes replay warmup, previous-signal audit and future labels.
        LocalDate auditFrom = settings.from().minusDays(properties.lookbackDays());
        LocalDate fetchTo = settings.to().plusDays(settings.futureCalendarDays());
        LocalDate yesterday = LocalDate.now(PanicHistoricalReplayRunner.MARKET_ZONE).minusDays(1);
        if (fetchTo.isAfter(yesterday)) fetchTo = yesterday;
        List<Candle> history = source.getDailyCandles(ticker, auditFrom.minusDays(properties.lookbackDays()), fetchTo)
                .stream().filter(c -> c.status() == CandleStatus.CLOSED)
                .sorted(Comparator.comparing(Candle::date)).toList();
        if (history.isEmpty()) throw new IllegalStateException("No closed history available");
        for (int i = 1; i < history.size(); i++) if (history.get(i - 1).date().equals(history.get(i).date()))
            throw new IllegalArgumentException("Duplicate historical session");
        MarketDataClient local = new MarketDataClient() {
            public List<StockSummary> listStocks() { throw new IllegalStateException("Explicit ticker audit must not discover universe"); }
            public List<Candle> getDailyCandles(String symbol, LocalDate from, LocalDate to) { return history; }
        };
        var signals = new PanicHistoricalReplayRunner(local, engine, strategy, entry, properties).run(
                new PanicHistoricalReplayRunner.Request(auditFrom, settings.to(), List.of(ticker),
                        settings.rankingMode(), settings.historicalProvider()));
        // Evaluation happens only after all signals have been generated. No label reaches the replay port.
        return new TickerResult(ticker, evaluate(signals, history, settings), null);
    }

    static List<Observation> evaluate(List<PanicHistoricalReplayRunner.Row> signals, List<Candle> history, Settings settings) {
        Map<LocalDate, Integer> index = new HashMap<>();
        for (int i = 0; i < history.size(); i++) index.put(history.get(i).date(), i);
        LocalDate lastQualified = null; Integer lastScore = null; Integer lastIndex = null;
        List<Observation> observations = new ArrayList<>();
        for (var row : signals) {
            int i = index.get(row.simulatedDate());
            BigDecimal r3 = forwardReturn(history, i, 3), r5 = forwardReturn(history, i, 5), r10 = forwardReturn(history, i, 10);
            boolean complete = r5 != null && r10 != null;
            boolean strong = r5 != null && r5.compareTo(settings.return5ThresholdPercent()) >= 0
                    || r10 != null && r10.compareTo(settings.return10ThresholdPercent()) >= 0;
            boolean qualified = row.result().status() == SignalStatus.QUALIFIED;
            Classification classification = strong ? qualified ? Classification.DETECTED_EARLY
                    : lastQualified == null ? Classification.MISSED_OPPORTUNITY : Classification.LOST_AFTER_DETECTION
                    : !complete ? Classification.INSUFFICIENT_FUTURE_DATA
                    : qualified ? Classification.FALSE_POSITIVE : Classification.NO_OPPORTUNITY;
            boolean rsiOnly = strong && !qualified && row.blockingChecks().equals(List.of("rsiInsideRange"))
                    && row.result().score() >= settings.momentum().minimumQualifiedScore()
                    && row.result().technicalAnalysis() != null
                    && row.result().technicalAnalysis().rsi9().compareTo(BigDecimal.valueOf(70)) > 0;
            if (!row.simulatedDate().isBefore(settings.from())) observations.add(new Observation(row, r3, r5, r10,
                    futureDate(history, i, 3), futureDate(history, i, 5), futureDate(history, i, 10), classification,
                    lastQualified, lastScore, lastIndex == null ? null : i - lastIndex, rsiOnly));
            if (qualified) { lastQualified = row.simulatedDate(); lastScore = row.result().score(); lastIndex = i; }
        }
        return List.copyOf(observations);
    }

    private static LocalDate futureDate(List<Candle> history, int i, int horizon) {
        return i + horizon < history.size() ? history.get(i + horizon).date() : null;
    }
    private static BigDecimal forwardReturn(List<Candle> history, int i, int horizon) {
        if (i + horizon >= history.size() || history.get(i).close().signum() <= 0) return null;
        return history.get(i + horizon).close().subtract(history.get(i).close()).multiply(BigDecimal.valueOf(100))
                .divide(history.get(i).close(), 8, RoundingMode.HALF_UP);
    }

    /** Cross-ticker ranking reuses the original selector over frozen signals, without recalculating indicators. */
    public Map<String, Integer> ranks(List<TickerResult> completed, Settings settings) {
        Map<LocalDate, Map<String, ScannerResult>> days = new TreeMap<>();
        completed.forEach(t -> t.observations().forEach(o -> days.computeIfAbsent(o.signal().simulatedDate(), d -> new LinkedHashMap<>())
                .put(t.ticker(), o.signal().result())));
        Map<String, Integer> ranks = new HashMap<>();
        days.forEach((date, results) -> {
            Clock clock = Clock.fixed(date.atTime(LocalTime.MAX).atZone(PanicHistoricalReplayRunner.MARKET_ZONE).toInstant(),
                    PanicHistoricalReplayRunner.MARKET_ZONE);
            MarketDataClient frozen = new MarketDataClient() {
                public List<StockSummary> listStocks() { return results.keySet().stream().map(t -> new StockSummary(t,t,"STOCK",true)).toList(); }
                public List<Candle> getDailyCandles(String t, LocalDate f, LocalDate end) { throw new IllegalStateException("Ranking must not access prices"); }
            };
            var analyze = new AnalyzeStockUseCase(frozen, engine, strategy, entry, properties, clock) {
                @Override public ScannerResult execute(String ticker) { return results.get(ticker); }
            };
            var selected = new ScanB3MarketUseCase(frozen, analyze, clock).execute(new MarketScanCriteria(
                    properties.minAverageFinancialVolume20(), properties.minimumQualifiedScore(), 0, List.of(),
                    settings.rankingMode(), properties.maxMarketScanResults())).results();
            for (int i = 0; i < selected.size(); i++) ranks.put(date + "/" + selected.get(i).ticker(), i + 1);
        });
        return ranks;
    }
}
