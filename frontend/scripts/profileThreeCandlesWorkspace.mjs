import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from '../node_modules/typescript/lib/typescript.js';
const compile = path => ts.transpileModule(readFileSync(new URL(path,import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText;
const load = path => {const exports={};runInNewContext(compile(path),{exports,Intl,Date,Set,Map,Error});return exports;};
const engine=load('../src/features/threecandles/models/FibonacciMovementEngine.ts');
const patterns=load('../src/features/threecandles/models/patternPresentation.ts');
const view=JSON.parse(readFileSync(new URL('../src/features/threecandles/validation/pattern-detector/1155.json',import.meta.url),'utf8'));
const count=1219, seed=view.patternStudy.candidates;
view.patternStudy.candidates=Array.from({length:count},(_,i)=>({...seed[i%seed.length],id:`benchmark-${i}`}));
let formatters=0,elements=0;
const measuredIntl={DateTimeFormat:function(...args){formatters++;return new Intl.DateTimeFormat(...args);}};
const exports={};
runInNewContext(compile('../src/features/threecandles/components/ThreeCandlesWorkspace.tsx'),{exports,Intl:measuredIntl,Date,Error,require(name){
 if(name==='react')return {useState:v=>[typeof v==='function'?v():v,()=>{}],useMemo:fn=>fn()};
 if(name==='@mui/material')return new Proxy({},{get:(_,key)=>key});
 if(name==='react/jsx-runtime')return {jsx:(type,props)=>{elements++;return {type,props};},jsxs:(type,props)=>{elements++;return {type,props};}};
 if(name.includes('FibonacciMovementEngine'))return engine;
 if(name.includes('patternPresentation'))return patterns;
 if(name.includes('ThreeCandlesChart'))return {ThreeCandlesChart:'Chart'};
 if(name.includes('DowDebugPanel'))return {DowDebugPanel:'DowPanel'};
 if(name.includes('ExperimentalChopPanel'))return {ExperimentalChopPanel:'ChopPanel'};
 throw Error(name);
}});
const start=performance.now();exports.ThreeCandlesWorkspace({controller:{},view,candleDisplayTimeZone:'UTC'});
const report={scenario:'Synthetic 1219 candidates, all layers off, diagnostics closed; real workspace render with lightweight JSX host, not browser timing',milliseconds:performance.now()-start,formatters,elements};
mkdirSync(new URL('../../docs/three-candles-performance/',import.meta.url),{recursive:true});
writeFileSync(new URL(`../../docs/three-candles-performance/${process.argv[2]??'profile'}.json`,import.meta.url),JSON.stringify(report,null,2));
